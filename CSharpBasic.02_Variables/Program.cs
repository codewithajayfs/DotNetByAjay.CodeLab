namespace CSharpBasic._02_Variables;

class Program
{
    static void Main(string[] args)
    {
        // Variable Declaration 

        // String Type Variable
        string firstname;
        string lastname;

        // Interger Type Variable
        int num1, num2, sum;

        // Variable Initialization
        int number1 = 100;
        int number2 = 100;
        int summ = number1 + number2;

        // Variable name can start with letter or underscore
        int age;
        string _name;

        // Variable name can't start with a special character
        // int #grade; -Wrong

        //Variable can't start with number
        // int 2grade; - Wrong


        //Variable name can contain letters, digits, and underscore
        int grade2;

        // No space
        // int grade 2; -Wrong

        //Variable names are case sensitive
        int phone, Phone;
    }
}
